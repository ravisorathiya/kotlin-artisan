<#
.SYNOPSIS
  Copies the {{FEATURE}} files from ./reference into a project (see overview.md). Generated by `artisan make:bundle`.

.DESCRIPTION
  DRY RUN by default: prints what would happen. Add -Apply to write files.
  - Kind "new": files the original project didn't have; they are simply added.
  - Kind "modified": FULL-FILE snapshots of files that already exist in the project. They are only replaced with
    -IncludeModified (a *.bak_{{FEATURE}} backup is written first). If the target project's copy of such a file has
    changes of its own, do NOT replace it: merge by hand using overview.md (diff it against the .txt snapshot).

  ProjectRoot defaults to the folder that contains the "ai" module (this script lives in {{SCRIPT_DIR}}).

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File apply_bundle.ps1                            # dry run
  powershell -ExecutionPolicy Bypass -File apply_bundle.ps1 -Apply                     # add new files only
  powershell -ExecutionPolicy Bypass -File apply_bundle.ps1 -Apply -IncludeModified    # also replace modified files
#>
param(
    [string]$ProjectRoot = (Resolve-Path (Join-Path $PSScriptRoot '{{UP}}')).Path,
    [switch]$Apply,
    [switch]$IncludeModified
)

$ref = Join-Path $PSScriptRoot 'reference'

$files = @(
{{FILES}}
)

Write-Host "Project root : $ProjectRoot"
Write-Host ("Mode         : " + $(if ($Apply) { 'APPLY' } else { 'DRY RUN (add -Apply to write)' }))
Write-Host ""

$changed = 0
$failed = 0
foreach ($f in $files) {
    $src = Join-Path $ref $f.Src
    $dst = Join-Path $ProjectRoot $f.Dst
    if (-not (Test-Path -LiteralPath $src)) { Write-Host ("MISSING SNAPSHOT  " + $f.Src) -ForegroundColor Red; continue }

    $exists = Test-Path -LiteralPath $dst
    $same = $exists -and ((Get-FileHash -LiteralPath $src).Hash -eq (Get-FileHash -LiteralPath $dst).Hash)
    if ($same) { Write-Host ("identical         " + $f.Dst); continue }

    $write = $false
    if ($f.Kind -eq 'new') {
        $status = if ($exists) { 'REPLACE (new file differs)' } else { 'ADD' }
        $write = $true
    } elseif (-not $exists) {
        $status = 'TARGET MISSING (moved or renamed in this project: find it and merge by hand)'
    } elseif ($IncludeModified) {
        $status = 'REPLACE (backup .bak_{{FEATURE}})'
        $write = $true
    } else {
        $status = 'DIFFERS - merge via overview.md, or re-run with -IncludeModified'
    }
    Write-Host ("{0,-17} {1}" -f $status.Split(' ')[0], $f.Dst + "   [" + $status + "]")

    if ($write -and $Apply) {
        try {
            $dir = Split-Path $dst -Parent
            if (-not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Path $dir -Force -ErrorAction Stop | Out-Null }
            if ($exists) { Copy-Item -LiteralPath $dst ($dst + '.bak_{{FEATURE}}') -Force -ErrorAction Stop }
            Copy-Item -LiteralPath $src $dst -Force -ErrorAction Stop
            $changed++
        } catch {
            $failed++
            Write-Host ("FAILED            " + $f.Dst + "  -> " + $_.Exception.Message) -ForegroundColor Red
        }
    }
}

Write-Host ""
if ($Apply) {
    if ($failed -gt 0) {
        Write-Host "$changed file(s) written, $failed FAILED (see above; a very long project path can pass the 260-char Windows limit)." -ForegroundColor Red
    } else {
        Write-Host "Done: $changed file(s) written. Next: build (gradlew assembleDebug) and check overview.md's device checklist." -ForegroundColor Green
    }
} else {
    Write-Host "Dry run only. Nothing was written."
}
